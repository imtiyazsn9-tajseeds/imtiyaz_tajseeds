/**
 * Lists the photos that ship with the site (public/assets/products and /gallery) into
 * worker/static-images.js, so the admin photo picker can show them. Run by `npm run build`.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const images = [];
for (const folder of ['products', 'gallery']) {
  const dir = path.join(root, 'public', 'assets', folder);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir).sort()) {
    if (/\.(png|jpe?g|webp|gif|svg)$/i.test(file)) images.push(`assets/${folder}/${file}`);
  }
}

fs.writeFileSync(
  path.join(root, 'worker', 'static-images.js'),
  `// Generated by scripts/build-image-manifest.js. Do not edit.\nexport default ${JSON.stringify(images, null, 2)};\n`
);
console.log(`Listed ${images.length} shipped photos`);
